package com.taskmind.domain.model;

/**
 * Кому предназначена запись — комментарий или событие ленты.
 *
 * <p>Пока в системе нет роли «заказчик», поэтому фактически всё создаётся как
 * {@link #PUBLIC}. Поле заводится заранее: досыпать колонку в {@code comments} и
 * {@code activityLog} после того, как там появятся данные, дороже, чем провести
 * его сейчас одним значением по умолчанию. Когда появится внешний участник,
 * ленту и список комментариев можно будет фильтровать по этому полю, а не
 * «потом разберёмся по тексту».
 */
public enum Visibility {

    /** Видно всем участникам проекта. Значение по умолчанию. */
    PUBLIC,

    /** Только команда: внутренние заметки, обсуждение бюджета и рисков. */
    INTERNAL,

    /** Служебное событие, порождённое системой, а не человеком. */
    SYSTEM;

    /** Неизвестное или отсутствующее значение из БД трактуем как {@link #PUBLIC}. */
    public static Visibility fromString(String raw) {
        if (raw == null || raw.isBlank()) {
            return PUBLIC;
        }
        try {
            return valueOf(raw);
        } catch (IllegalArgumentException e) {
            return PUBLIC;
        }
    }
}
